/**
 * Button visual variant.
 *
 * 'error' is the library-wide canonical name for the destructive/failure
 * variant (matching alert/toast/badge/progress); 'danger' is a deprecated
 * alias kept for backwards compatibility and renders identically.
 */
export type ButtonVariant = 'primary' | 'secondary' | 'outline' | 'ghost' | 'danger' | 'error' | 'link';
export type ButtonType = 'button' | 'submit' | 'reset';
